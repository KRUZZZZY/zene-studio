/*! The three effects' dialogs are generated by the effect (EffectControls::createView), so a real effect is loaded
 *  from the build's own modules and its dialog built over it. What each must do: carry one control per parameter,
 *  every control on the effect's own model (so the dialog, the file, undo and plugin.param_* move one state), the
 *  hint text a user reads while turning a knob, and respond to the keyboard like every other knob. Both directions
 *  are held: a value set through plugin.param_set shows on the dialog's knob, and a key pressed on the knob is
 *  read back by plugin.param_get. */

