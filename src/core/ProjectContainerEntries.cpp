bool deriveContainerEntries( const QByteArray& document,
	const QString& contentElementName,
	std::vector<std::pair<QString, QByteArray>>* entries, QString* error )
{
	if( entries == nullptr )
	{
		setError( error, QStringLiteral( "no destination for the derived entries" ) );
		return false;
	}

	QDomDocument dom;
	QDomElement root;
	QDomElement content;
	if( !openDocument( document, contentElementName, &dom, &root, &content, error ) )
	{
		return false;
	}

	DocumentIndex index;
	QVector<QString> entryNames;
	QStringList skipNames;
	if( !validatedIndexRows( root, &index, &entryNames, &skipNames, error ) )
	{
		return false;
	}

	SectionRanges found;
	if( !scanSectionRanges( document, contentElementName, skipNames, found ) )
	{
		// The two refusals scanSectionRanges() names - a document it cannot
		// follow to its end, a begin offset it cannot recover - are the same
		// ones reduceDocumentSections() answers with unchanged bytes; here they
		// are answered with no entries at all.
		setError( error, QStringLiteral( "the document could not be scanned to its "
			"end, so its sections cannot be cut without guessing" ) );
		return false;
	}
	if( !indexMatchesRanges( found, index, contentElementName, error ) ) { return false; }

	std::vector<std::pair<QString, QByteArray>> derived;
	if( !cutEntries( document, found, entryNames, &derived, error ) ) { return false; }

	// The skeleton's interior must be whitespace-only now that the indexed
	// sections are out of it: anything still in there is a child the index did
	// not name (an element, a comment), and splicing the entries back before
	// the close tag would move the sections past it - so the refusal is what
	// keeps the byte-identity promise true rather than probable.
	qint64 innerBegin = 0;
	qint64 innerEnd = 0;
	if( !locateContentInterior( derived.at( 0 ).second, contentElementName,
		&innerBegin, &innerEnd, error ) )
	{
		return false;
	}

	*entries = std::move( derived );
	return true;
}


bool reassembleContainerDocument( const std::vector<std::pair<QString, QByteArray>>& entries,
	const QString& contentElementName, QByteArray* document, QString* error )
{
	if( document == nullptr )
	{
		setError( error, QStringLiteral( "no destination for the reassembled document" ) );
		return false;
	}
	if( entries.empty() )
	{
		setError( error, QStringLiteral( "the container's entries are empty, so there "
			"is nothing to reassemble" ) );
		return false;
	}

	QByteArray skeleton;
	QHash<QString, QByteArray> bodies;
	if( !partitionEntries( entries, &skeleton, &bodies, error ) ) { return false; }

	QDomDocument dom;
	QDomElement root;
	QDomElement content;
	if( !openDocument( skeleton, contentElementName, &dom, &root, &content, error ) )
	{
		return false;
	}

	DocumentIndex index;
	QVector<QString> entryNames;
	QStringList scanNames; // a throwaway: the reassembler scans nothing
	if( !validatedIndexRows( root, &index, &entryNames, &scanNames, error ) ) { return false; }
	if( !entriesMatchIndex( bodies, entryNames, error ) ) { return false; }

	qint64 innerBegin = 0;
	qint64 innerEnd = 0;
	if( !locateContentInterior( skeleton, contentElementName, &innerBegin, &innerEnd, error ) )
	{
		return false;
	}

	// The splice: the skeleton up to the close tag, then every section body in
	// INDEX order - each body looked up by its generated name, which is why the
	// incoming pair order was never consulted - then the close tag and the
	// rest. Raw bytes in, raw bytes out, nothing re-serialised (the guarantee
	// is written up on deriveContainerEntries in ProjectContainer.h).
	QByteArray rebuilt = skeleton.left( innerEnd );
	for( const QString& entryName : entryNames )
	{
		rebuilt.append( bodies.value( entryName ) );
	}
	rebuilt.append( skeleton.mid( innerEnd ) );

	*document = std::move( rebuilt );
	return true;
}

